"""Phase 57 Plan 01 (D-04/D-05/D-06): the repo's FIRST test cross-checking
two independently-sourced EXTERNAL witnesses.

This is the direct answer to the failure mode named in the roadmap: "four
test modules, a golden argv fixture, and a CLI double all agreed with each
other, and none of them could validate a server-side enum." Every existing
aux test in this repo (test_phase55_auxiliary_metering.py,
test_compat_meter_completion_aux.py, test_phase56_aux_atomicity.py,
test_phase56_dry_run.py) asserts the emitted `--operation-type` value
against a Python literal the repo itself authored. That proves argv shape,
flag ordering, atomicity, and mirror-leak avoidance -- it proves nothing
about whether Revenium's server would actually ACCEPT the value, because a
fixture that agrees with itself cannot catch a server-side contract it has
never seen.

The risk this module is designed against: passing while only ever
consulting ONE witness dressed up as two. It is trivial to write a test
that *looks* like a two-witness check but actually just asserts the same
literal twice under different names. Every assertion below is built to make
that specific failure mode structurally impossible:

  - Witness A (the pinned, GENERATED extract at
    tests/fixtures/spec/operation-type-enum.json, produced by
    tests/extract_operation_type_enum.py from the vendored 2.20.0-SNAPSHOT
    OAS) is loaded by `_load_witness_a()`, a `json.load` over a file path.
  - Witness B (the verbatim server rejection transcript already committed
    at docs/comprehensive-roi-proof.md:191) is loaded by
    `_load_witness_b()`, a `re.search` over that document's live text at
    test-run time.
  - The two loaders share no parser, no constant, and no helper. Neither
    witness's value list appears as a Python literal ANYWHERE in this
    module -- if you are tempted to add one while debugging a failure here,
    that is the exact defect this module exists to prevent.
  - The emitted value under test is captured by driving the REAL
    `skills/revenium/scripts/hermes-report.sh` end to end (via
    tests/_compat_helpers.py, the same harness Phase 55/56 use), and is
    selected by its `--task-type` value matching `^aux_` -- NEVER by its
    `--operation-type` value, which would make the membership assertion
    circular (selecting the very thing you are about to assert membership
    of).
"""
from __future__ import annotations

import json
